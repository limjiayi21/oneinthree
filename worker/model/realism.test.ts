import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import type { ClientEventType, ManStance, WorldContext } from '../../shared/types';
import { groundedLine, lineAcknowledges } from './address';
import { heuristicWomanRead } from '../read';
import { Rng } from './rng';
import { decideWoman, initialWomanState } from './woman';

const ctx = (elapsed: number): WorldContext => ({
  elapsed,
  distanceToMan: 2,
  progress: 0.3,
  playerSpeed: 1.1,
  facingMan: true,
  manBlocking: false,
  oppositeSidewalk: false,
});

interface Beat {
  event: ClientEventType;
  text?: string;
}

interface Script {
  name: string;
  beats: Beat[];
  /** Stances that must not appear on the first reply. */
  notFirst?: ManStance[];
}

const SCRIPTS: Script[] = [
  { name: 'Greeting', beats: [{ event: 'speech', text: 'hello' }], notFirst: ['back_off', 'gone', 'escalate', 'intimidate'] },
  { name: 'Hi', beats: [{ event: 'speech', text: 'hi' }], notFirst: ['back_off', 'gone', 'escalate'] },
  { name: 'What', beats: [{ event: 'speech', text: 'what?' }], notFirst: ['back_off', 'gone', 'escalate'] },
  { name: 'Sorry', beats: [{ event: 'speech', text: 'sorry' }], notFirst: ['back_off', 'gone', 'escalate'] },
  { name: 'Um', beats: [{ event: 'speech', text: 'um' }], notFirst: ['back_off', 'gone', 'escalate'] },
  { name: 'Silence', beats: [{ event: 'silence' }], notFirst: ['back_off', 'gone', 'escalate'] },
  { name: 'Ignored twice', beats: [{ event: 'silence' }, { event: 'silence' }], notFirst: ['back_off', 'gone'] },
  { name: 'Polite no', beats: [{ event: 'speech', text: 'No thank you, have a good night.' }], notFirst: ['back_off', 'gone', 'escalate'] },
  { name: 'Firm once', beats: [{ event: 'speech', text: 'Leave me alone.' }], notFirst: ['back_off', 'gone', 'escalate'] },
  { name: 'Firm twice', beats: [{ event: 'speech', text: 'Leave me alone.' }, { event: 'speech', text: 'I said leave me alone.' }] },
  { name: 'Joking', beats: [{ event: 'speech', text: 'Haha, you are funny.' }], notFirst: ['back_off', 'gone', 'escalate'] },
  { name: 'Calls for help', beats: [{ event: 'speech', text: 'I am calling the police.' }] },
  { name: 'Walks away', beats: [{ event: 'sped_up' }], notFirst: ['escalate'] },
  { name: 'Sarcasm', beats: [{ event: 'speech', text: 'Nice try, creep.' }], notFirst: ['back_off', 'gone', 'escalate'] },
  { name: 'Apology with words', beats: [{ event: 'speech', text: 'Sorry, I did not hear you.' }], notFirst: ['back_off', 'gone', 'escalate'] },
  { name: 'On the phone', beats: [{ event: 'speech', text: 'I am on the phone with my friend.' }], notFirst: ['back_off', 'gone', 'escalate'] },
  { name: 'Boyfriend', beats: [{ event: 'speech', text: 'My boyfriend is waiting for me.' }], notFirst: ['back_off', 'gone', 'escalate'] },
];

function runScript(seed: number, script: Script): { stances: ManStance[]; lines: string[] } {
  const rng = new Rng(seed);
  let state = initialWomanState('persistent');
  const opened = decideWoman(state, { event: 'begin', ctx: ctx(4) }, rng);
  state = opened.state;
  const stances: ManStance[] = [];
  const lines: string[] = [];
  script.beats.forEach((beat, i) => {
    const read = beat.text ? heuristicWomanRead(beat.text) : null;
    const out = decideWoman(
      state,
      { event: beat.event, ctx: ctx(12 + i * 9), text: beat.text, strategyProbs: read?.strategyProbs, signals: read?.signals },
      rng,
    );
    state = out.state;
    const stance = out.decision?.stance ?? state.stance;
    stances.push(stance);
    const move = beat.text ? (read?.strategy === 'firm_boundary' ? 'firm' : read?.strategy === 'hostile' ? 'hostile' : read?.strategy === 'excuse' ? 'excuse' : read?.strategy === 'polite_deflect' ? 'polite' : read?.strategy === 'threaten_attention' ? 'police' : 'engage') : 'silence';
    const line = groundedLine({ stance, move, text: beat.text ?? '', rng }) ?? '(he says nothing)';
    lines.push(line);
  });
  return { stances, lines };
}

describe('realism harness', () => {
  it('keeps greetings and early pushback off retreat, and writes a transcript', () => {
    const blocks: string[] = [
      '# Realism transcripts',
      '',
      'Generated by `worker/model/realism.test.ts`. Seeded model only: no Clef, no judge, no line model. Disposition is persistent. Seed 11. Each line is the grounded reply for the stance the machine picked, so it has to mention what she said.',
      '',
    ];
    for (const script of SCRIPTS) {
      const { stances, lines } = runScript(11, script);
      if (script.notFirst) {
        expect(script.notFirst, script.name).not.toContain(stances[0]);
      }
      script.beats.forEach((beat, i) => {
        if (!beat.text) return;
        expect(lineAcknowledges(lines[i], beat.text), `${script.name}: ${lines[i]}`).toBe(true);
        if (script.notFirst) expect(lines[i], script.name).not.toMatch(/your loss/i);
      });
      blocks.push(`## ${script.name}`, '');
      script.beats.forEach((beat, i) => {
        const said = beat.text ? `"${beat.text}"` : `(${beat.event})`;
        blocks.push(`- She: ${said}`, `- He (${stances[i]}): ${lines[i]}`, '');
      });
    }
    writeFileSync(new URL('../../docs/realism-transcripts.md', import.meta.url), blocks.join('\n'));
    expect(SCRIPTS.length).toBeGreaterThanOrEqual(15);
  });
});
